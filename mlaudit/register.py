"""Write a findings register (Excel) from an audit results folder.

Usage: python -m mlaudit.register results/<run>/<target> OUT.xlsx [--title "..."] [--author "..."]
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.worksheet.datavalidation import DataValidation

from .findings import SEVERITY_MEANING

THIN = Side(style="thin", color="000000")
INPUT_FILL = PatternFill("solid", start_color="F2F2F2", end_color="F2F2F2")
STATUS = ["Open", "Accepted", "Disputed", "Fixed", "Will not fix"]
CHECK_KIND = {"static": "Code reading", "dynamic": "Run in a copy"}
CATEGORY_LABEL = {
    "leakage": "Data leakage", "execution_integrity": "Model execution integrity",
    "failure_handling": "Failure handling", "reproducibility": "Reproducibility",
    "dependency": "Dependencies", "testing": "Automated tests", "integration": "Integration",
}
PRIORITY = {"Critical": 1, "High": 2, "Medium": 3, "Low": 4}


def _sheet(ws, header, rows, widths, font):
    ws.append(header)
    for c in ws[1]:
        c.font = Font(name=font, bold=True, color="000000")
        c.border = Border(bottom=THIN, top=THIN)
        c.alignment = Alignment(vertical="top", wrap_text=True)
    for r in rows:
        ws.append(r)
    for row in ws.iter_rows(min_row=2):
        for c in row:
            c.font = Font(name=font, color="000000")
            c.alignment = Alignment(vertical="top", wrap_text=True)
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[ws.cell(row=1, column=i).column_letter].width = w
    ws.freeze_panes = "A2"
    ws.page_setup.orientation = "landscape"
    ws.page_setup.paperSize = ws.PAPERSIZE_A4
    ws.page_setup.fitToWidth = 1
    ws.page_setup.fitToHeight = 0
    ws.sheet_properties.pageSetUpPr.fitToPage = True
    ws.print_title_rows = "1:1"


def build(res_dir: Path, out: Path, title: str, author: str, font: str = "Helvetica") -> int:
    findings = json.loads((res_dir / "findings.json").read_text())
    audit = json.loads((res_dir / "audit.json").read_text())
    wb = Workbook()
    ws = wb.active
    ws.title = "Read me"
    integ = audit["integrity"]
    lines = [
        [title],
        [""],
        ["What this is", "One row per finding from a read-only audit. Nothing in the audited repository was changed."],
        ["Audited folder", audit["root"].split("/")[-1]],
        ["Integrity check", f"{integ['files_before']} files hashed before and after; "
                            f"{'no file added, removed or changed' if integ['unchanged'] else 'CHANGES FOUND'}."],
        ["Findings", f"{len(findings)} in total: " + ", ".join(f"{audit['finding_counts'].get(s, 0)} {s}" for s in ("Critical", "High", "Medium", "Low"))],
        ["Data", "All data are synthetic, generated by the platform's own seeded generator."],
        ["How to use", "Sort or filter the Findings sheet. The shaded columns (Status, Owner, Response) are for your team."],
        ["Sheets", "Findings; Severity scale; Checks run"],
    ]
    for ln in lines:
        ws.append(ln)
    ws["A1"].font = Font(name=font, bold=True, size=12, color="000000")
    for row in ws.iter_rows(min_row=3):
        for c in row:
            c.font = Font(name=font, color="000000", bold=(c.column == 1))
            c.alignment = Alignment(vertical="top", wrap_text=True)
    ws.column_dimensions["A"].width = 18
    ws.column_dimensions["B"].width = 100

    fs = wb.create_sheet("Findings")
    rows = []
    for f in findings:
        loc = f["file"] or "(behaviour when run)"
        if f["file"] and f["line"]:
            loc = f"{f['file']}:{f['line']}"
        rows.append([f["id"], f["severity"], PRIORITY[f["severity"]], CATEGORY_LABEL.get(f["category"], f["category"]),
                     f["title"].replace("`", ""), loc, f["detail"].replace("`", ""), f["recommendation"],
                     CHECK_KIND.get(f["kind"], f["kind"]), "Open", "", ""])
    _sheet(fs, ["ID", "Severity", "Priority", "Area", "Finding", "Location", "Evidence", "Recommendation (not applied)",
                "How found", "Status", "Owner", "Response"], rows,
           [6, 10, 8, 18, 36, 26, 60, 44, 13, 11, 12, 30], font)
    n = len(rows) + 1
    dv = DataValidation(type="list", formula1='"' + ",".join(STATUS) + '"', allow_blank=True)
    fs.add_data_validation(dv)
    dv.add(f"J2:J{n}")
    for r in range(2, n + 1):
        for col in "JKL":
            fs[f"{col}{r}"].fill = INPUT_FILL
    fs.auto_filter.ref = f"A1:L{n}"

    sv = wb.create_sheet("Severity scale")
    _sheet(sv, ["Severity", "Meaning", "Priority"], [[k, v, PRIORITY[k]] for k, v in SEVERITY_MEANING.items()], [12, 80, 10], font)

    ck = wb.create_sheet("Checks run")
    cr = []
    inv = audit["inventory"]
    cr.append(["Inventory", f"{inv['source_files']} source files ({inv['source_lines']:,} code lines), {inv['test_files']} test files, "
                            f"{inv['test_functions']} test functions; entry points: {', '.join(inv['entry_points'])}"])
    for r in audit.get("runs", []):
        cr.append([f"Run {r['name']}", f"exit {r['returncode']}, {r['seconds']} s"])
    if "split" in audit:
        cr.append(["Patient overlap", json.dumps(audit["split"])])
    if "metrics" in audit:
        rep, calc = audit["metrics"].get("reported", {}), audit["metrics"].get("recomputed", {})
        cr.append(["Metric recomputation", f"AUROC reported {rep.get('auroc')}, recomputed {calc.get('auroc')}"])
    if "rerun" in audit:
        cr.append(["Rerun comparison", ", ".join(f"{k}: {'same' if v else 'differs'}" for k, v in audit["rerun"]["files"].items())])
    if "temporal" in audit and "comparison" in audit["temporal"]:
        c = audit["temporal"]["comparison"]
        cr.append(["Post-prediction-time probe", f"AUROC {c['auroc_a']:.3f} with all data, {c['auroc_b']:.3f} with post-time records removed"])
    if "inference" in audit:
        inf = audit["inference"]
        if "consistency" in inf:
            cr.append(["Validated vs served scores", json.dumps(inf["consistency"])])
        for p in inf.get("perturbations", []):
            cr.append([f"Bad input: {p['description']}", f"{p['outcome']} (exit {p['returncode']})"])
    if audit.get("tests"):
        t = audit["tests"]
        cov = t.get("coverage") or {}
        cr.append(["Test suite", f"{t.get('summary')}; statement coverage {cov.get('total', 0):.0f}%"])
    if audit.get("mutation"):
        m = audit["mutation"]
        cr.append(["Mutation sample", f"{m['killed']} of {m['run']} mutants caught by the tests (seed {m['seed']})"])
    if audit.get("vulnerabilities"):
        v = audit["vulnerabilities"]
        cr.append(["Known vulnerabilities", f"{v.get('status')}; {len(v.get('scanned', []))} pinned packages scanned on {v.get('date')}"])
    _sheet(ck, ["Check", "Result"], cr, [30, 110], font)

    wb.properties.creator = author
    wb.properties.lastModifiedBy = author
    wb.properties.title = title
    out.parent.mkdir(parents=True, exist_ok=True)
    wb.save(out)
    return len(rows)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("results", type=Path)
    ap.add_argument("out", type=Path)
    ap.add_argument("--title", default="Findings register")
    ap.add_argument("--author", default="")
    a = ap.parse_args(argv)
    print(build(a.results, a.out, a.title, a.author))


if __name__ == "__main__":
    main()
